test('original article actions autosave, sync selected sentences and finish reading', async ({ page }) => {
  const state = await mockStudy(page)
  await page.goto('/passages')
  const reader = page.locator('.passage-annotator')
  await expect(reader).toBeVisible()
  await reader.press('ControlOrMeta+End')
  await reader.press('End')
  await reader.press('Enter')
  await reader.pressSequentially('A new reading note.')
  await expect.poll(() => state.passages[0].body_text).toContain('A new reading note.')
  await page.getByRole('button', { name: '同步 2 句', exact: true }).last().click()
  await expect.poll(() => state.passages[0].selected_sentence_ids.length).toBe(2)
  await expect(reader).toContainText('A new reading note.')
  await page.getByRole('button', { name: '完成阅读', exact: true }).click()
  await expect.poll(() => state.passages[0].status).toBe('done')
  expect(state.unhandled).toEqual([])
})

test('original sentence form preserves failed input and supports retry', async ({ page }) => {
  const state = await mockStudy(page)
  state.failCreate = true
  await page.goto('/create')
  const input = page.locator('.sentence-editor-text').first()
  await input.fill('A sentence worth returning to.')
  await page.getByRole('button', { name: '保存句子', exact: true }).click()
  await expect(page.getByText('保存暂时失败，请重试', { exact: true })).toBeVisible()
  await expect(input).toHaveText('A sentence worth returning to.')
  state.failCreate = false
  await page.getByRole('button', { name: '保存句子', exact: true }).click()
  await expect.poll(() => state.sentences[0].text).toBe('A sentence worth returning to.')
  await expect(input).toBeEmpty()
})

test('all original screens fit desktop and phone viewports in both themes', async ({ page }, testInfo) => {
  test.setTimeout(60000)
  const state = await mockStudy(page)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  for (const theme of ['light', 'dark']) {
    for (const [name, path] of [['review', '/'], ['library', '/library'], ['passages', '/passages'], ['create', '/create'], ['stats', '/stats']]) {
      await page.goto(path)
      await expect(page.locator('.english-workspace h1')).toBeVisible()
      await expect(page.getByRole('navigation', { name: '英语复习导航' }).getByRole('button')).toHaveText(['复习', '句库', '阅读', '统计'])
      await setTheme(page, theme)
      if (name === 'review') await expect(cardsFor(page).first()).toBeVisible()
      if (name === 'library') await expect(page.locator('.english-workspace article').first()).toBeVisible()
      await page.evaluate(() => document.fonts.ready)
      expect(await page.locator('.english-workspace').evaluate(element => element.scrollWidth <= element.clientWidth + 1), `${name} ${theme} overflows`).toBe(true)
      await page.screenshot({ path: testInfo.outputPath(`${name}-${theme}.png`), animations: 'disabled' })
      if (name === 'passages') {
        await page.locator('.passage-annotator').scrollIntoViewIfNeeded()
        await page.screenshot({ path: testInfo.outputPath(`reading-${theme}.png`), animations: 'disabled' })
      }
    }
  }
  expect(errors).toEqual([])
  expect(state.unhandled).toEqual([])
})

