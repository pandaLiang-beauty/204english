import { test, expect } from '@playwright/test'
import { mockStudy } from './fixtures.js'

const cardsFor = page => page.locator('.english-review-card')
const translationFor = card => card.locator('.review-card-support > section').first().locator('.mt-1')
const setTheme = (page, theme) => page.getByRole('button', { name: theme === 'dark' ? '深色主题' : '浅色主题', exact: true }).click()

test('original day and night controls persist the chosen appearance', async ({ page }) => {
  await mockStudy(page)
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await expect(cardsFor(page).first()).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await setTheme(page, 'light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await setTheme(page, 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})

test('original review preserves translation space and independent repeated arrangements', async ({ page }) => {
  const state = await mockStudy(page)
  await page.goto('/')
  const cards = cardsFor(page)
  const first = cards.nth(0)
  const second = cards.nth(1)
  await expect(cards).toHaveCount(20)
  await expect(translationFor(first)).toBeHidden()
  await expect(first.locator('.review-card-heading button')).toHaveText(['播放', '完成并下一句', '显示翻译', '编辑'])
  const firstNode = await first.elementHandle()
  const position = () => second.evaluate(element => element.getBoundingClientRect().top + document.querySelector('.english-workspace').scrollTop)
  const originalPosition = await position()
  await first.getByRole('button', { name: '显示翻译', exact: true }).click()
  await expect(translationFor(first)).toBeVisible()
  await expect(translationFor(first)).toContainText('真正的理解')
  expect(await position()).toBeCloseTo(originalPosition, 1)
  await first.getByRole('button', { name: '隐藏翻译', exact: true }).click()
  await expect(translationFor(first)).toBeHidden()
  expect(await position()).toBeCloseTo(originalPosition, 1)
  await first.getByRole('button', { name: '播放', exact: true }).click()
  await expect.poll(() => state.events.length).toBe(1)
  expect(state.events[0].complete_round_item).toBe(false)
  expect(state.completed.size).toBe(0)
  await first.getByRole('button', { name: '完成并下一句', exact: true }).click()
  await expect.poll(() => state.completed.has(1000)).toBe(true)
  await expect(second.getByText('当前', { exact: true })).toBeVisible()
  expect(await firstNode.evaluate(element => element.isConnected)).toBe(true)
  expect(state.completed.has(1012)).toBe(false)
  await cards.nth(12).getByRole('button', { name: '完成并下一句', exact: true }).click()
  await expect.poll(() => state.completed.has(1012)).toBe(true)
  expect(state.completed.size).toBe(2)
  expect(state.unhandled).toEqual([])
})

