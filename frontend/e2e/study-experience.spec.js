test('original word-meaning editor saves without changing the sentence', async ({ page }) => {
  const state = await mockStudy(page)
  await page.goto('/library')
  const first = page.locator('.english-workspace article').first()
  await first.getByTitle('编辑句子', { exact: true }).click()
  const meanings = first.getByPlaceholder('word=释义', { exact: true })
  await meanings.fill((await meanings.inputValue()).replace('connections=联系；句中指不同知识之间的关联', 'connections=联系；知识之间的关联'))
  await first.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect.poll(() => state.sentences[0].word_translations.connections).toBe('联系；知识之间的关联')
  expect(state.sentences[0].text).toContain('**connections**')
})

test('320px phones keep the original top navigation and sentence actions reachable', async ({ page }) => {
  await mockStudy(page)
  await page.setViewportSize({ width: 320, height: 720 })
  await page.goto('/')
  const first = cardsFor(page).first()
  await expect(first).toBeVisible()
  const actions = page.locator('.english-top-nav button').or(first.locator('.review-card-heading button'))
  for (const button of await actions.all()) {
    const box = await button.boundingBox()
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(320)
  }
  expect(await page.locator('.english-workspace').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
})
